import 'dart:convert';
import 'package:relic/relic.dart';
import 'package:http/http.dart' as http;
import '../../domain/entities/provider/provider_config.dart';
import '../../application/containers/metadata_usecases.dart';
import '../../service_locator.dart';
import '../../infrastructure/protocols/conduit/conduit_protocol.dart';
import '../../infrastructure/protocols/conduit/http_conduit_protocol.dart';
import '../middlewares/auth_middleware.dart';

/// [ARCH: PRESENTATION_CONTROLLER]
/// ROLE: Controller for Platform Metadata and Configuration.
/// CONTRACT: Maps HTTP requests for provider settings and dynamic metadata to [MetadataUseCases].
/// CONSTRAINTS: Purely for data delivery. Handles user context resolution from [userIdProperty].
class MetadataController {
  final MetadataUseCases _metadata = sl<MetadataUseCases>();

  Future<Response> getProviders(Request request) async {
    final userId = userIdProperty.get(request);
    final result = await _metadata.getProviderMetadata.execute(userId);
    return result.fold(
      (failure) => Response.internalServerError(
        body: Body.fromString(
          jsonEncode({
            'error': 'Failed to fetch metadata',
            'details': failure.message,
          }),
          mimeType: MimeType.json,
        ),
      ),
      (metadata) {
        final jsonList = metadata.map((m) => m.toMap()).toList();
        return Response.ok(
          body: Body.fromString(
            jsonEncode({
              'data': jsonList,
              'meta': {
                'dataType': 'list:provider_metadata',
                'timestamp': DateTime.now().toIso8601String(),
              },
            }),
            mimeType: MimeType.json,
          ),
        );
      },
    );
  }

  Future<Response> getCapabilities(Request request) async {
    try {
      final capabilities = await _metadata.getProviderCapabilities.execute();
      return Response.ok(
        body: Body.fromString(
          jsonEncode({
            'data': capabilities,
            'meta': {
              'dataType': 'list:provider_capability',
              'timestamp': DateTime.now().toIso8601String(),
            },
          }),
          mimeType: MimeType.json,
        ),
      );
    } catch (e) {
      return Response.internalServerError(
        body: Body.fromString(
          jsonEncode({
            'error': 'Failed to fetch provider capabilities',
            'details': e.toString(),
          }),
          mimeType: MimeType.json,
        ),
      );
    }
  }

  Future<Response> getConfigs(Request request) async {
    final result = await _metadata.getProviderConfigs.execute();
    if (result.isLeft()) {
      final failure = result.getLeft().toNullable()!;
      return Response.internalServerError(
        body: Body.fromString(
          jsonEncode({
            'error': 'Failed to fetch provider configurations',
            'details': failure.message,
          }),
          mimeType: MimeType.json,
        ),
      );
    }
    final configs = result.getRight().toNullable()!;
    final jsonList = configs.map((c) => c.toMap()).toList();
    final statusResult = await _metadata.getSystemStatus.execute();
    final isSystemConfigured = statusResult.getOrElse((_) => false);

    return Response.ok(
      body: Body.fromString(
        jsonEncode({
          'data': jsonList,
          'meta': {
            'dataType': 'list:provider_config',
            'isSystemConfigured': isSystemConfigured,
            'timestamp': DateTime.now().toIso8601String(),
          },
        }),
        mimeType: MimeType.json,
      ),
    );
  }

  Future<Response> getStatus(Request request) async {
    try {
      final statusResult = await _metadata.getSystemStatus.execute();
      final isSystemConfigured = statusResult.getOrElse((_) => false);

      return Response.ok(
        body: Body.fromString(
          jsonEncode({
            'data': {
              'isSystemConfigured': isSystemConfigured,
            },
            'meta': {
              'dataType': 'system_status',
              'timestamp': DateTime.now().toIso8601String(),
            },
          }),
          mimeType: MimeType.json,
        ),
      );
    } catch (e) {
      return Response.internalServerError(
        body: Body.fromString(
          jsonEncode({
            'error': 'Failed to fetch system status',
            'details': e.toString(),
          }),
          mimeType: MimeType.json,
        ),
      );
    }
  }

  Future<Response> saveConfig(Request request) async {
    try {
      final bodyStr = await request.readAsString();
      final data = jsonDecode(bodyStr) as Map<String, dynamic>;

      // Use the class fromMap method generated by dart_mappable
      final config = ProviderConfigMapper.fromMap(data);

      final result = await _metadata.saveProviderConfig.execute(config);

      return result.fold(
        (failure) => Response.internalServerError(
          body: Body.fromString(
            jsonEncode({'error': failure.message}),
            mimeType: MimeType.json,
          ),
        ),
        (savedConfig) => Response.ok(
          body: Body.fromString(
            jsonEncode({'data': savedConfig.toMap()}),
            mimeType: MimeType.json,
          ),
        ),
      );
    } catch (e) {
      return Response.badRequest(
        body: Body.fromString(
          jsonEncode({
            'error': 'Invalid request body',
            'details': e.toString(),
          }),
          mimeType: MimeType.json,
        ),
      );
    }
  }

  Future<Response> testConfig(Request request) async {
    try {
      final bodyStr = await request.readAsString();
      final data = jsonDecode(bodyStr) as Map<String, dynamic>;
      final config = ProviderConfigMapper.fromMap(data);

      print('TESTING CONFIG: ${config.name} at ${config.baseUrl}');

      if (config.id == 'phorge' || config.id == 'phabricator') {
        final apiToken =
            config.settings['api.token'] ?? config.settings['apiToken'];

        if (apiToken == null || apiToken.toString().isEmpty) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'API Token is missing',
              }),
              mimeType: MimeType.json,
            ),
          );
        }

        final ConduitProtocol client = HttpConduitProtocol(
          baseUrl: config.baseUrl,
          apiToken: apiToken.toString(),
        );

        try {
          final result = await client
              .call('user.whoami', {})
              .timeout(const Duration(seconds: 10));
          client.dispose();

          final userName =
              result['userName'] ??
              result['realName'] ??
              result['value'] ??
              'Unknown User';
          final phid = result['phid'] ?? result['phid'] ?? 'Unknown PHID';

          return Response.ok(
            body: Body.fromString(
              jsonEncode({
                'data': {
                  'status': 'connected',
                  'message': 'Successfully connected as $userName ($phid)',
                },
              }),
              mimeType: MimeType.json,
            ),
          );
        } catch (e) {
          client.dispose();
          String details = e.toString();

          if (details.contains('ERR-CONDUIT-AUTH')) {
            details = 'Invalid API Token (ERR-CONDUIT-AUTH)';
          } else if (details.contains('Failed host lookup')) {
            details =
                'Could not resolve host: ${config.baseUrl}. Check the URL and DNS settings.';
          } else if (details.contains('Connection refused')) {
            details =
                'Connection refused at ${config.baseUrl}. The server might be down or blocked by a firewall.';
          } else if (details.contains('TimeoutException')) {
            details =
                'Connection timed out. Check your network or Phorge server status.';
          }

          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({'error': 'Connection failed', 'details': details}),
              mimeType: MimeType.json,
            ),
          );
        }
      }

      if (config.id == 'github') {
        final token =
            (config.settings['api.token'] ?? config.settings['token'] ?? '')
                .toString()
                .trim();
        if (token.isEmpty) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'GitHub token is missing',
              }),
              mimeType: MimeType.json,
            ),
          );
        }

        final configuredApiBaseUrl = (config.settings['apiBaseUrl'] ?? '')
            .toString()
            .trim();
        final apiBaseUrl =
            (configuredApiBaseUrl.isEmpty
                    ? 'https://api.github.com'
                    : configuredApiBaseUrl)
                .replaceAll(RegExp(r'/+$'), '');
        final uri = Uri.parse('$apiBaseUrl/user');

        try {
          final response = await http
              .get(
                uri,
                headers: {
                  'Accept': 'application/vnd.github+json',
                  'Authorization': 'Bearer $token',
                  'User-Agent': 'dab-api',
                  'X-GitHub-Api-Version': '2022-11-28',
                },
              )
              .timeout(const Duration(seconds: 10));

          if (response.statusCode == 200) {
            final body = jsonDecode(response.body) as Map<String, dynamic>;
            final login = body['login']?.toString() ?? 'unknown';
            return Response.ok(
              body: Body.fromString(
                jsonEncode({
                  'data': {
                    'status': 'connected',
                    'message': 'Successfully connected as $login',
                  },
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details':
                    'GitHub API returned ${response.statusCode}. Verify token and API base URL.',
              }),
              mimeType: MimeType.json,
            ),
          );
        } catch (e) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'GitHub connectivity test failed: $e',
              }),
              mimeType: MimeType.json,
            ),
          );
        }
      }

      if (config.id == 'slack') {
        final token =
            (config.settings['botToken'] ??
                    config.settings['api.token'] ??
                    config.settings['token'] ??
                    '')
                .toString()
                .trim();
        if (token.isEmpty) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'Slack bot token is missing',
              }),
              mimeType: MimeType.json,
            ),
          );
        }

        final apiBaseUrl =
            ((config.settings['apiBaseUrl'] ?? '').toString().trim().isEmpty
                    ? 'https://slack.com/api'
                    : (config.settings['apiBaseUrl'] ?? '').toString().trim())
                .replaceAll(RegExp(r'/+$'), '');
        final uri = Uri.parse('$apiBaseUrl/auth.test');
        try {
          final response = await http
              .post(
                uri,
                headers: {
                  'Authorization': 'Bearer $token',
                  'Content-Type': 'application/json; charset=utf-8',
                },
              )
              .timeout(const Duration(seconds: 10));

          if (response.statusCode != 200) {
            return Response.badRequest(
              body: Body.fromString(
                jsonEncode({
                  'error': 'Connection failed',
                  'details': 'Slack API returned ${response.statusCode}.',
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          final body = jsonDecode(response.body) as Map<String, dynamic>;
          if (body['ok'] != true) {
            final error = body['error']?.toString() ?? 'unknown_error';
            return Response.badRequest(
              body: Body.fromString(
                jsonEncode({
                  'error': 'Connection failed',
                  'details': 'Slack auth.test failed: $error',
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          final teamName = body['team']?.toString() ?? 'unknown workspace';
          return Response.ok(
            body: Body.fromString(
              jsonEncode({
                'data': {
                  'status': 'connected',
                  'message':
                      'Successfully connected to Slack workspace $teamName',
                },
              }),
              mimeType: MimeType.json,
            ),
          );
        } catch (e) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'Slack connectivity test failed: $e',
              }),
              mimeType: MimeType.json,
            ),
          );
        }
      }

      if (config.id == 'teams') {
        final tenantId = (config.settings['tenantId'] ?? '').toString().trim();
        final clientId = (config.settings['clientId'] ?? '').toString().trim();
        final clientSecret =
            (config.settings['clientSecret'] ?? '').toString().trim();
        if (tenantId.isEmpty || clientId.isEmpty || clientSecret.isEmpty) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details':
                    'Teams tenantId, clientId, and clientSecret are required',
              }),
              mimeType: MimeType.json,
            ),
          );
        }

        try {
          final tokenUri = Uri.parse(
            'https://login.microsoftonline.com/$tenantId/oauth2/v2.0/token',
          );
          final tokenResponse = await http
              .post(
                tokenUri,
                headers: {
                  'Content-Type': 'application/x-www-form-urlencoded',
                },
                body: {
                  'client_id': clientId,
                  'client_secret': clientSecret,
                  'grant_type': 'client_credentials',
                  'scope': 'https://graph.microsoft.com/.default',
                },
              )
              .timeout(const Duration(seconds: 12));

          if (tokenResponse.statusCode < 200 ||
              tokenResponse.statusCode >= 300) {
            return Response.badRequest(
              body: Body.fromString(
                jsonEncode({
                  'error': 'Connection failed',
                  'details':
                      'Azure AD token request failed (${tokenResponse.statusCode}). Verify tenant and app registration.',
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          final tokenBody =
              jsonDecode(tokenResponse.body) as Map<String, dynamic>;
          final accessToken = tokenBody['access_token']?.toString().trim();
          if (accessToken == null || accessToken.isEmpty) {
            return Response.badRequest(
              body: Body.fromString(
                jsonEncode({
                  'error': 'Connection failed',
                  'details': 'Azure AD did not return an access token',
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          final orgResponse = await http
              .get(
                Uri.parse('https://graph.microsoft.com/v1.0/organization'),
                headers: {
                  'Authorization': 'Bearer $accessToken',
                  'Accept': 'application/json',
                },
              )
              .timeout(const Duration(seconds: 10));

          if (orgResponse.statusCode != 200) {
            return Response.badRequest(
              body: Body.fromString(
                jsonEncode({
                  'error': 'Connection failed',
                  'details':
                      'Microsoft Graph returned ${orgResponse.statusCode}. Check app permissions (e.g. Organization.Read.All).',
                }),
                mimeType: MimeType.json,
              ),
            );
          }

          final orgBody =
              jsonDecode(orgResponse.body) as Map<String, dynamic>;
          final orgs = orgBody['value'];
          final orgName =
              (orgs is List && orgs.isNotEmpty && orgs.first is Map)
                  ? (orgs.first as Map)['displayName']?.toString() ??
                      'organization'
                  : 'organization';

          return Response.ok(
            body: Body.fromString(
              jsonEncode({
                'data': {
                  'status': 'connected',
                  'message':
                      'Successfully connected to Microsoft Teams ($orgName)',
                },
              }),
              mimeType: MimeType.json,
            ),
          );
        } catch (e) {
          return Response.badRequest(
            body: Body.fromString(
              jsonEncode({
                'error': 'Connection failed',
                'details': 'Teams connectivity test failed: $e',
              }),
              mimeType: MimeType.json,
            ),
          );
        }
      }

      // Fallback for other providers (Generic ping or mock)
      await Future.delayed(const Duration(seconds: 1));

      bool success = true;
      String? errorMessage;

      if (!config.isActive) {
        success = false;
        errorMessage = 'Provider is not active';
      } else if (config.baseUrl.isEmpty) {
        success = false;
        errorMessage = 'Base URL is missing';
      }

      if (success) {
        return Response.ok(
          body: Body.fromString(
            jsonEncode({
              'data': {
                'status': 'connected',
                'message': 'Successfully pinged ${config.name}',
              },
            }),
            mimeType: MimeType.json,
          ),
        );
      } else {
        return Response.badRequest(
          body: Body.fromString(
            jsonEncode({'error': 'Connection failed', 'details': errorMessage}),
            mimeType: MimeType.json,
          ),
        );
      }
    } catch (e) {
      return Response.badRequest(
        body: Body.fromString(
          jsonEncode({
            'error': 'Invalid request body',
            'details': e.toString(),
          }),
          mimeType: MimeType.json,
        ),
      );
    }
  }

  Future<Response> getSystemSettings(Request request) async {
    final result = await _metadata.getSystemSettings.execute();
    return result.fold(
      (failure) => Response.internalServerError(
        body: Body.fromString(
          jsonEncode({
            'error': 'Failed to fetch system settings',
            'details': failure.message,
          }),
          mimeType: MimeType.json,
        ),
      ),
      (settings) => Response.ok(
        body: Body.fromString(
          jsonEncode({'data': settings}),
          mimeType: MimeType.json,
        ),
      ),
    );
  }

  Future<Response> saveSystemSettings(Request request) async {
    try {
      final bodyStr = await request.readAsString();
      final data = jsonDecode(bodyStr) as Map<String, dynamic>;
      final settings = data.map((key, value) => MapEntry(key, value.toString()));

      final result = await _metadata.saveSystemSettings.execute(settings);
      return result.fold(
        (failure) => Response.internalServerError(
          body: Body.fromString(
            jsonEncode({'error': failure.message}),
            mimeType: MimeType.json,
          ),
        ),
        (_) => Response.ok(
          body: Body.fromString(
            jsonEncode({'success': true}),
            mimeType: MimeType.json,
          ),
        ),
      );
    } catch (e) {
      return Response.badRequest(
        body: Body.fromString(
          jsonEncode({
            'error': 'Invalid request body',
            'details': e.toString(),
          }),
          mimeType: MimeType.json,
        ),
      );
    }
  }
}
